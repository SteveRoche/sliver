//! `/.sliver/theme.typ`: the app theme's colours under names notes can use
//! (`#import "/.sliver/theme.typ": ink, accent`). The vault keeps the light
//! version on disk, so notes that import it still compile outside the app
//! (with the vault as root) and export as light documents; the preview
//! compiles against the current theme's version instead.

pub const THEME_PATH: &str = "/.sliver/theme.typ";

struct Palette {
    ink: &'static str,
    paper: &'static str,
    muted: &'static str,
    accent: &'static str,
    error: &'static str,
    warning: &'static str,
    rule: &'static str,
}

// Keep in sync with the colour tokens in `src/App.css`.
const LIGHT: Palette = Palette {
    ink: "#0f0f0f",
    paper: "#ffffff",
    muted: "#6b6b6b",
    accent: "#396cd8",
    error: "#c62828",
    warning: "#b26a00",
    rule: "#d4d4d4",
};

const DARK: Palette = Palette {
    ink: "#e8e8e8",
    paper: "#2b2b2b",
    muted: "#9a9a9a",
    accent: "#6d9bff",
    error: "#ef5350",
    warning: "#ffb74d",
    rule: "#4a4a4a",
};

/// Source of [`THEME_PATH`] for a light or dark app theme.
pub fn theme_library(dark: bool) -> String {
    let p = if dark { &DARK } else { &LIGHT };
    // In the light theme everything is already on light paper.
    let untheme = if dark {
        "block(fill: light.paper, inset: 6pt, width: 100%, { set text(fill: light.ink); body })"
    } else {
        "body"
    };
    format!(
        r#"// Generated by Sliver: the colours of the app's {mode} theme. Do not edit.
// Use them by name, e.g. `#import "/.sliver/theme.typ": ink, accent`.
#let dark = {dark}
#let ink = rgb("{ink}")
#let paper = rgb("{paper}")
#let muted = rgb("{muted}")
#let accent = rgb("{accent}")
#let error = rgb("{error}")
#let warning = rgb("{warning}")
#let rule = rgb("{rule}")
// The light theme's colours, whatever the current theme.
#let light = (ink: rgb("{light_ink}"), paper: rgb("{light_paper}"))
// Shows `body` as on light paper in every theme, for content drawn for a
// white page (diagrams, images with black lines).
#let untheme(body) = {untheme}
"#,
        mode = if dark { "dark" } else { "light" },
        ink = p.ink,
        paper = p.paper,
        muted = p.muted,
        accent = p.accent,
        error = p.error,
        warning = p.warning,
        rule = p.rule,
        light_ink = LIGHT.ink,
        light_paper = LIGHT.paper,
    )
}
